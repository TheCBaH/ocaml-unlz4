(* embed DIR: prints an OCaml module holding DIR/manifest.txt and the fixture files it lists, so
   every backend (including Melange, which has no file I/O) replays the same corpus. Fails if a
   listed file is missing or its size differs from the manifest. *)

let read_file path =
  let ic = open_in_bin path in
  Fun.protect
    ~finally:(fun () -> close_in ic)
    (fun () -> really_input_string ic (in_channel_length ic))

let field key line =
  let prefix = key ^ "=" in
  List.find_map
    (fun w ->
      if String.length w > String.length prefix && String.sub w 0 (String.length prefix) = prefix
      then Some (String.sub w (String.length prefix) (String.length w - String.length prefix))
      else None)
    (String.split_on_char ' ' line)

let () =
  let dir = Sys.argv.(1) in
  let manifest = read_file (Filename.concat dir "manifest.txt") in
  let files =
    List.filter_map
      (fun line ->
        if String.length line > 8 && String.sub line 0 8 = "fixture " then
          match (field "file" line, field "size" line) with
          | Some file, Some size ->
              let data = read_file (Filename.concat dir file) in
              if String.length data <> int_of_string size then
                failwith
                  (Printf.sprintf "%s: size %d, manifest says %s" file (String.length data) size);
              Some (file, data)
          | _ -> failwith ("malformed manifest line: " ^ line)
        else None)
      (String.split_on_char '\n' manifest)
  in
  print_string "(* Generated by tools/embed.ml from test/corpus; do not edit. *)\n\n";
  Printf.printf "let manifest = %S\n\nlet files = [\n" manifest;
  List.iter (fun (f, d) -> Printf.printf "  (%S, %S);\n" f d) files;
  print_string "]\n"
